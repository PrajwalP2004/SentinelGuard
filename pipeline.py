#!/usr/bin/env python3
"""
Unified Multi-Phase Software Architecture & Security Analysis Pipeline.

Sequential Execution Model:
The pipeline operates strictly sequentially under a prerequisite execution model.
Each phase depends directly upon outputs generated by preceding upstream phases.
Selecting a specific target phase via --phase executes all required prerequisite
phases in dependency order before executing and returning the target phase output:
    - Phase 0: Repository Ingestion (stops after ingestion if --phase 0)
    - Phase 1: Project Reconstruction (requires Phase 0)
    - Phase 2: Requirements Extraction & Security Assessment (requires Phases 0-1)
    - Phase 3 / 3a: Red Team Security Analysis (requires Phases 0-2)
    - Phase 4 / 4a: Blue Team Defensive Analysis (requires Phases 0-3a)
    - Phase 5 / 5a: Security Retest & Verification (requires Phases 0-4a)
    - Phase 6: Code Smell & Maintainability Analysis (requires Phases 0-1)
    - Phase 7 / 7a: Cross-Domain Engineering Analysis (requires Phases 0-6)
    - Phase 8: Recommendation Engine (requires Phases 0-7a)
    - Phase 9 / report: Final Architecture & Security Report (requires Phases 0-8)
    - all: Executes the complete end-to-end pipeline (Phases 0 through 9) and
           returns a consolidated multi-phase record.

Usage:
    python pipeline.py --source https://github.com/org/repo.git
    python pipeline.py --source /path/to/repo.zip --phase 0
    python pipeline.py --source /path/to/repo --phase 8
    python pipeline.py --source /path/to/repo --phase report --format markdown
    python pipeline.py --source . --phase all --output results.json
"""

