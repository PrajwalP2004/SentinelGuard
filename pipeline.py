class PipelineExecutionError(Exception):
    """Raised when a specific phase in the pipeline fails during execution."""

    def __init__(self, phase: str, operation: str, original_error: Exception):
        self.phase = phase
        self.operation = operation
        self.original_error = original_error
        super().__init__(f"Phase {phase} failed during '{operation}': {original_error}")


class PhaseOutputValidationError(PipelineExecutionError):
    """Raised when a phase output fails contract validation."""

    def __init__(
        self,
        phase: str,
        operation: str,
        field: str,
        expected: str,
        actual: str,
        detail: str = "",
    ):
        self.field = field
        self.expected = expected
        self.actual = actual
        self.detail = detail
        if field:
            desc = f"field '{field}' expected {expected}, got {actual}."
        else:
            desc = f"expected {expected}, got {actual}."
        if detail:
            desc = f"{desc} {detail}".strip()
        super().__init__(
            phase=phase,
            operation=operation,
            original_error=ValueError(f"Contract violation: {desc}"),
        )


def validate_phase_output(
    phase: str,
    operation: str,
    output: Any,
    expected_type: type = dict,
    required_fields: Optional[Dict[str, type]] = None,
) -> Any:
    """
    Validates that a phase's output satisfies its structural contract before downstream consumption.

    Args:
        phase: The phase identifier (e.g., '0', '1', '3a').
        operation: The operation or agent step that generated the output.
        output: The output returned by the phase agent.
        expected_type: The expected top-level type (default dict).
        required_fields: Mapping of field_name -> expected_type for required fields.

    Returns:
        The validated output.

    Raises:
        PhaseOutputValidationError: If the output fails contract validation.
    """
    if not isinstance(output, expected_type):
        raise PhaseOutputValidationError(
            phase=phase,
            operation=operation,
            field="",
            expected=expected_type.__name__,
            actual=type(output).__name__,
            detail=f"Top-level output must be a {expected_type.__name__}, got {type(output).__name__}."
        )

    if required_fields and isinstance(output, dict):
        for field, f_type in required_fields.items():
            if field not in output:
                raise PhaseOutputValidationError(
                    phase=phase,
                    operation=operation,
                    field=field,
                    expected=f_type.__name__,
                    actual="missing",
                    detail=f"Required field '{field}' is missing from phase output."
                )
            val = output[field]
            if not isinstance(val, f_type):
                raise PhaseOutputValidationError(
                    phase=phase,
                    operation=operation,
                    field=field,
                    expected=f_type.__name__,
                    actual=type(val).__name__,
                    detail=f"Field '{field}' must be a {f_type.__name__}, got {type(val).__name__}."
                )

    return output


