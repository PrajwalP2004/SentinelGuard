def safe_write_output(output_path: str, content: str) -> None:
    """Safely and atomically writes output content to destination path."""
    abs_path = os.path.abspath(output_path)
    parent_dir = os.path.dirname(abs_path)
    if parent_dir and not os.path.exists(parent_dir):
        os.makedirs(parent_dir, exist_ok=True)

    temp_path = None
    try:
        # Write to temporary file in the same directory for atomic os.replace()
        fd, temp_path = tempfile.mkstemp(
            prefix=".tmp_output_",
            dir=parent_dir or ".",
            text=True
        )
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())

        os.replace(temp_path, abs_path)
        temp_path = None
    except Exception as err:
        if temp_path and os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except OSError:
                pass
        raise OSError(f"Failed to write output to '{output_path}': {err}") from err


def cleanup_temp_dir(temp_dir: Optional[str], source: Optional[str] = None) -> None:
    """Safely cleans up a temporary repository directory without masking exceptions or affecting persistent sources."""
    if not temp_dir:
        return

    try:
        resolved_temp = os.path.abspath(temp_dir)
        # Guard: never clean up if path does not exist or is not a directory
        if not os.path.exists(resolved_temp) or not os.path.isdir(resolved_temp):
            return

        # Guard: never clean up user-provided source path
        if source:
            resolved_source = os.path.abspath(source)
            if resolved_temp == resolved_source:
                return

        # Guard: never clean filesystem root or drive root
        if resolved_temp in ("/", "\\") or (len(resolved_temp) <= 3 and resolved_temp[1:3] in (":\\", ":/")):
            return

        def _remove_readonly(func, path, excinfo):
            try:
                os.chmod(path, stat.S_IWRITE)
                func(path)
            except Exception:
                raise

        shutil.rmtree(resolved_temp, onerror=_remove_readonly)
    except Exception as cleanup_err:
        print(
            f"Warning: Failed to clean up temporary directory '{temp_dir}': {cleanup_err}",
            file=sys.stderr,
        )


def run_pipeline(source: str, source_type: str = None, phase: str = "all") -> Any:
    current_phase = "0"
    current_operation = "initializing ingestion"
    temp_dir_to_clean = None

    try:
        # 1. Infer source_type if not provided
        current_phase = "0"
        current_operation = "inferring repository source type"
        if not source_type:
            clean_s = source.strip()
            if clean_s.startswith(("http://", "https://", "git@")) or clean_s.endswith(".git") or "github.com" in clean_s:
                source_type = "github"
            elif clean_s.lower().endswith(".zip"):
                source_type = "zip"
            elif os.path.isdir(clean_s):
                source_type = "dir"
            elif not os.path.exists(clean_s) and "/" not in clean_s and "\\" not in clean_s:
                # Bare username candidate (e.g. 'PrajwalP2004')
                source_type = "github"
            else:
                raise ValueError(f"Unable to infer source type for '{source}'.")

        agent0 = RepositoryIngestionAgent()

        # Phase 0: Ingestion
        current_phase = "0"
        current_operation = "obtaining repository"
        repo_path, is_temp = agent0.obtain_repository(source_type=source_type, source=source)
        if is_temp:
            temp_dir_to_clean = repo_path

        current_operation = "generating repository inventory"
        metadata = {"source_type": source_type, "source": source}
        phase0_output = agent0.inventory(root_path=repo_path, metadata=metadata)
        validate_phase_output(
            phase="0",
            operation="generating repository inventory",
            output=phase0_output,
            expected_type=dict,
            required_fields={"file_inventory": list}
        )

        if phase == "0":
            return phase0_output

        # Phase 1: Project Reconstruction
        current_phase = "1"
        current_operation = "reconstructing project architecture"
        agent1 = ProjectReconstructionAgent(root_path=repo_path, phase0_inventory=phase0_output)
        phase1_output = agent1.reconstruct()
        validate_phase_output(
            phase="1",
            operation="reconstructing project architecture",
            output=phase1_output,
            expected_type=dict,
            required_fields={"components": list}
        )

        if phase == "1":
            return phase1_output

        # Phase 2: Requirement Extraction
        current_phase = "2"
        current_operation = "extracting requirements"
        agent2_req = RequirementsEngineeringAgent(
            root_path=repo_path,
            phase0_inventory=phase0_output,
            phase1_reconstruction=phase1_output
        )
        phase2_requirements = agent2_req.extract_requirements()
        validate_phase_output(
            phase="2",
            operation="extracting requirements",
            output=phase2_requirements,
            expected_type=list
        )

        if phase == "2":
            return phase2_requirements

        # Phase 2 Assessment
        current_operation = "performing initial security assessment"
        agent2_sec = SecurityAssessmentAgent(phase1_reconstruction=phase1_output)
        phase2_assessment = agent2_sec.assess()
        validate_phase_output(
            phase="2",
            operation="performing initial security assessment",
            output=phase2_assessment,
            expected_type=dict
        )

        # Phase 3A: Red Team Security Analysis
        current_phase = "3a"
        current_operation = "red team security analysis"
        agent3a = RedTeamSecurityAgent(
            root_path=repo_path,
            phase0_inventory=phase0_output,
            phase1_reconstruction=phase1_output,
            phase2_requirements=phase2_requirements
        )
        phase3a_output = agent3a.analyze()
        validate_phase_output(
            phase="3a",
            operation="red team security analysis",
            output=phase3a_output,
            expected_type=dict,
            required_fields={"findings": list}
        )

        if phase in ("3", "3a"):
            return phase3a_output

        # Phase 4A: Blue Team Defensive Analysis
        current_phase = "4a"
        current_operation = "blue team defensive analysis"
        agent4a = BlueTeamDefensiveAgent(
            root_path=repo_path,
            phase1_reconstruction=phase1_output,
            phase2_requirements=phase2_requirements,
            phase3a_findings=phase3a_output["findings"]
        )
        phase4a_output = agent4a.analyze()
        validate_phase_output(
            phase="4a",
            operation="blue team defensive analysis",
            output=phase4a_output,
            expected_type=dict,
            required_fields={"remediation_plans": list}
        )

        if phase in ("4", "4a"):
            return phase4a_output

        # Phase 5A: Security Retest
        current_phase = "5a"
        current_operation = "security retest verification"
        agent5a = SecurityRetestAgent(
            root_path=repo_path,
            phase3a_findings=phase3a_output["findings"],
            phase4a_remediations=phase4a_output["remediation_plans"]
        )
        phase5a_output = agent5a.retest()
        validate_phase_output(
            phase="5a",
            operation="security retest verification",
            output=phase5a_output,
            expected_type=dict,
            required_fields={"retest_results": list}
        )

        if phase in ("5", "5a"):
            return phase5a_output

        # Phase 6: Code Smell & Maintainability Analysis
        current_phase = "6"
        current_operation = "code smell and maintainability analysis"
        agent6 = CodeSmellAnalysisAgent(
            root_path=repo_path,
            phase1_reconstruction=phase1_output
        )
        phase6_output = agent6.analyze()
        validate_phase_output(
            phase="6",
            operation="code smell and maintainability analysis",
            output=phase6_output,
            expected_type=dict,
            required_fields={"code_smells": list}
        )

        if phase == "6":
            return phase6_output

        # Phase 7: Cross-Domain Software Engineering Analysis
        current_phase = "7"
        current_operation = "cross-domain engineering analysis"
        agent7 = CrossDomainAnalysisAgent(
            phase1_reconstruction=phase1_output,
            phase2_requirements=phase2_requirements,
            phase3a_findings=phase3a_output["findings"],
            phase4a_remediations=phase4a_output["remediation_plans"],
            phase5a_retest=phase5a_output,
            phase6_smells=phase6_output["code_smells"]
        )
        phase7_output = agent7.analyze()
        validate_phase_output(
            phase="7",
            operation="cross-domain engineering analysis",
            output=phase7_output,
            expected_type=dict,
            required_fields={"cross_domain_relationships": list}
        )

        if phase in ("7", "7a"):
            return phase7_output

        # Phase 8: Senior Software Engineering Recommendation Engine
        current_phase = "8"
        current_operation = "generating prioritized recommendations"
        agent8 = RecommendationEngineAgent(
            phase1_reconstruction=phase1_output,
            phase2_requirements=phase2_requirements,
            phase3a_findings=phase3a_output["findings"],
            phase4a_remediations=phase4a_output["remediation_plans"],
            phase5a_retest=phase5a_output,
            phase6_smells=phase6_output["code_smells"],
            phase7_relationships=phase7_output["cross_domain_relationships"]
        )
        phase8_output = agent8.generate_recommendations()
        validate_phase_output(
            phase="8",
            operation="generating prioritized recommendations",
            output=phase8_output,
            expected_type=dict,
            required_fields={"recommendations": list}
        )

        if phase == "8":
            return phase8_output

        # Phase 9: Final Software Analysis Report
        current_phase = "9"
        current_operation = "compiling final report data"
        agent9 = FinalReportGeneratorAgent(
            phase0_inventory=phase0_output,
            phase1_reconstruction=phase1_output,
            phase2_requirements=phase2_requirements,
            phase2_assessment=phase2_assessment,
            phase3a_red_team=phase3a_output,
            phase4a_blue_team=phase4a_output,
            phase5a_retest=phase5a_output,
            phase6_smells=phase6_output,
            phase7_cross_domain=phase7_output,
            phase8_recommendations=phase8_output
        )
        phase9_report_data = agent9.generate_report_data()
        validate_phase_output(
            phase="9",
            operation="compiling final report data",
            output=phase9_report_data,
            expected_type=dict
        )

        current_operation = "generating final markdown report"
        phase9_markdown = agent9.generate_markdown_report()
        validate_phase_output(
            phase="9",
            operation="generating final markdown report",
            output=phase9_markdown,
            expected_type=str
        )

        if phase in ("9", "report"):
            return {
                "report_data": phase9_report_data,
                "markdown_report": phase9_markdown
            }

        # Phase 'all': Return combined multi-phase record
        return {
            "phase0_inventory": phase0_output,
            "phase1_reconstruction": phase1_output,
            "phase2_requirements": phase2_requirements,
            "phase2_security_assessment": phase2_assessment,
            "phase3a_red_team": phase3a_output,
            "phase4a_blue_team": phase4a_output,
            "phase5a_security_retest": phase5a_output,
            "phase6_code_smells": phase6_output,
            "phase7_cross_domain": phase7_output,
            "phase8_recommendations": phase8_output,
            "phase9_final_report": phase9_report_data,
            "phase9_markdown_report": phase9_markdown,
        }

    except Exception as exc:
        if isinstance(exc, PipelineExecutionError):
            raise
        raise PipelineExecutionError(current_phase, current_operation, exc) from exc
    finally:
        cleanup_temp_dir(temp_dir_to_clean, source=source)


def build_parser() -> argparse.ArgumentParser:
    """Builds and returns the command-line argument parser for the pipeline."""
    parser = argparse.ArgumentParser(
        description=(
            "Unified Multi-Phase Software Architecture and Security Pipeline. "
            "Sequential Execution Model: Selecting a target phase via --phase automatically executes all "
            "required prerequisite upstream phases in order before generating and returning the target output. "
            "Use --phase all to run the complete end-to-end pipeline (Phases 0 through 9), or --phase 9 / "
            "--phase report to execute all upstream analysis and generate the final report."
        )
    )
    parser.add_argument("--source", required=True, help="Repository source (GitHub URL, ZIP file, or local directory)")
    parser.add_argument("--source-type", choices=["github", "zip", "dir"], help="Source type (inferred if omitted)")
    parser.add_argument(
        "--phase",
        choices=["0", "1", "2", "3", "3a", "4", "4a", "5", "5a", "6", "7", "7a", "8", "9", "report", "all"],
        default="all",
        help=(
            "Target phase to execute and output. Sequential prerequisite execution: selecting a target phase "
            "executes all prerequisite upstream phases first (e.g., --phase 8 executes Phases 0 through 7 before "
            "returning Phase 8 recommendations; --phase 0 stops after ingestion). "
            "--phase all runs the complete pipeline (Phases 0-9). "
            "--phase 9 or --phase report executes all upstream phases and generates the final report."
        )
    )
    parser.add_argument("--format", choices=["json", "markdown"], default="json", help="Output format for Phase 9 or all")
    parser.add_argument("--output", help="Optional file path to write output")
    parser.add_argument(
        "--debug",
        action="store_true",
        default=False,
        help="Enable debug mode with detailed exception traceback on failure"
    )
    return parser


def main(argv: Optional[List[str]] = None):
    parser = build_parser()
    args = parser.parse_args(argv)

    try:
        result = run_pipeline(source=args.source, source_type=args.source_type, phase=args.phase)

        if args.phase in ("9", "report") and args.format == "markdown":
            final_text = result["markdown_report"]
        elif args.phase == "all" and args.format == "markdown":
            final_text = result["phase9_markdown_report"]
        else:
            final_text = json.dumps(result, indent=2)

        if args.output:
            safe_write_output(args.output, final_text)
            print(f"Pipeline output (Phase {args.phase}) saved to: {args.output}", file=sys.stderr)
        else:
            print(final_text)

    except PipelineExecutionError as exc:
        print(f"Pipeline error in Phase {exc.phase} during '{exc.operation}': {exc.original_error}", file=sys.stderr)
        if getattr(args, "debug", False):
            import traceback
            traceback.print_exc(file=sys.stderr)
        sys.exit(1)
    except Exception as exc:
        print(f"Pipeline error: {str(exc)}", file=sys.stderr)
        if getattr(args, "debug", False):
            import traceback
            traceback.print_exc(file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
